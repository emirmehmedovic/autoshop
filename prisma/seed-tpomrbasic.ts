async function main() {
  console.log('🌱 Uvoz proizvoda iz TP Omrbasic...')

  // Dohvati kategorije
  const categories = await prisma.category.findMany()
  const categoryMap = new Map(categories.map(c => [c.slug, c.id]))

  console.log('Pronadjene kategorije:', Array.from(categoryMap.keys()))

  let created = 0
  let skipped = 0

  for (const product of products) {
    const categoryId = categoryMap.get(product.categorySlug)

    if (!categoryId) {
      console.log(`⚠️ Kategorija ${product.categorySlug} nije pronadjena, preskacemo ${product.name}`)
      skipped++
      continue
    }

    try {
      await prisma.product.upsert({
        where: { sku: product.sku },
        update: {
          name: product.name,
          price: product.price,
          stock: product.stock,
          shortDesc: product.shortDesc,
          description: product.description,
          metaTitle: product.metaTitle,
          metaDesc: product.metaDesc,
          categoryId: categoryId,
        },
        create: {
          name: product.name,
          slug: product.slug,
          sku: product.sku,
          price: product.price,
          stock: product.stock,
          shortDesc: product.shortDesc,
          description: product.description,
          metaTitle: product.metaTitle,
          metaDesc: product.metaDesc,
          categoryId: categoryId,
          isActive: true,
          isFeatured: false,
        },
      })
      console.log(`✅ ${product.name}`)
      created++
    } catch (error) {
      console.error(`❌ Greska za ${product.name}:`, error)
      skipped++
    }
  }

  console.log(`\n🎉 Zavrseno! Kreirano: ${created}, Preskoceno: ${skipped}`)
}

main()
  .catch((e) => {
    console.error('❌ Greska:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
