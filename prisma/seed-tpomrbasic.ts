async function main() {
  console.log('🌱 Uvoz proizvoda iz TP Omrbasic...')

  // Dohvati kategorije
  const categories = await prisma.category.findMany()
  const categoryMap = new Map(categories.map(c => [c.slug, c.id]))

  console.log('Pronađene kategorije:', Array.from(categoryMap.keys()))

  let created = 0
  let skipped = 0

  for (const product of products) {
    const categoryId = categoryMap.get(product.categorySlug)

    if (!categoryId) {
      console.log(`⚠️ Kategorija ${product.categorySlug} nije pronađena, preskačemo ${product.name}`)
      skipped++
      continue
    }

    // Zaokruži cijenu na višu cijelu vrijednost
    const roundedPrice = Math.ceil(product.price)

    try {
      await prisma.product.upsert({
        where: { sku: product.sku },
        update: {
          name: product.name,
          price: roundedPrice,
          stock: product.stock,
          shortDesc: product.shortDesc,
          description: product.description,
          metaTitle: product.metaTitle,
          metaDesc: product.metaDesc,
          categoryId: categoryId,
        },
        create: {
          name: product.name,
          slug: product.slug,
          sku: product.sku,
          price: roundedPrice,
          stock: product.stock,
          shortDesc: product.shortDesc,
          description: product.description,
          metaTitle: product.metaTitle,
          metaDesc: product.metaDesc,
          categoryId: categoryId,
          isActive: true,
          isFeatured: false,
        },
      })
      console.log(`✅ ${product.name}`)
      created++
    } catch (error) {
      console.error(`❌ Greška za ${product.name}:`, error)
      skipped++
    }
  }

  console.log(`\n🎉 Završeno! Kreirano: ${created}, Preskočeno: ${skipped}`)
}

main()
  .catch((e) => {
    console.error('❌ Greška:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
